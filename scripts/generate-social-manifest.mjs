import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = path.join(projectRoot, "public", "social-content", "data");
const editionPattern = /^\d{4}-\d{2}-\d{2}\.json$/;

const files = (await readdir(dataDir))
  .filter((file) => editionPattern.test(file))
  .sort();

if (!files.length) {
  throw new Error("No dated social-content editions were found.");
}

const editions = [];
for (const file of files) {
  const parsed = JSON.parse(await readFile(path.join(dataDir, file), "utf8"));
  const week = file.replace(/\.json$/, "");
  if (week !== parsed.week) {
    throw new Error(`${file}: 檔名與內部 week 欄位不符（${parsed.week}）`);
  }
  // Every edition is on the canonical schema, so no shape fallback: a file
  // that does not match is a mistake to surface, not to paper over.
  if (!Array.isArray(parsed.items) || parsed.items.length === 0) {
    throw new Error(`${file}: 缺少 items 陣列`);
  }
  const readyCount = parsed.items.filter((entry) => entry.status === "Ready").length;

  editions.push({
    week,
    readyCount,
    dataUrl: `/social-content/data/${file}`,
  });
}

const latest = editions.at(-1);
const manifest = {
  generatedFrom: "public/social-content/data/YYYY-MM-DD.json",
  latest,
  editions: editions.toReversed(),
};

await writeFile(
  path.join(dataDir, "latest.json"),
  `${JSON.stringify(manifest, null, 2)}\n`,
);

const generatedModule = `// Generated by scripts/generate-social-manifest.mjs. Do not edit manually.\n` +
  `export const latestSocialEdition = ${JSON.stringify(latest, null, 2)} as const;\n` +
  `export const socialEditionWeeks = ${JSON.stringify(editions.map((edition) => edition.week).toReversed(), null, 2)} as const;\n`;

await writeFile(
  path.join(projectRoot, "app", "data", "social-latest.generated.ts"),
  generatedModule,
);

console.log(`Social manifest: ${latest.week} (${latest.readyCount} ready)`);
